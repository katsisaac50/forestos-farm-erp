#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const root = path.resolve(__dirname, '..');
const script = path.join(__dirname, 'phase205_authoritative_lockfile_handoff.js');
const reportPath = path.join(root, 'PHASE205_AUTHORITATIVE_LOCKFILE_HANDOFF_REPORT.json');
let passed = 0;
function test(name, fn) { fn(); passed++; console.log('PASS ' + name); }
const src = fs.readFileSync(script, 'utf8');
test('script exists', () => assert.ok(fs.existsSync(script)));
test('requires explicit repository path', () => assert.match(src, /--repo/));
test('requires expected remote', () => assert.match(src, /--expected-remote/));
test('requires pinned commit', () => assert.match(src, /--commit/));
test('checks exact configured origin', () => assert.match(src, /configuredOrigin/));
test('resolves commit to full hash', () => assert.match(src, /rev-parse', '--verify/));
test('reads manifest from pinned commit', () => assert.match(src, /apps\/api\/package\.json/));
test('reads lockfile from pinned commit', () => assert.match(src, /apps\/api\/package-lock\.json/));
test('checks pinned manifest against current manifest', () => assert.match(src, /currentManifestMatchesPinnedSource/));
test('checks lockfile dependency alignment', () => assert.match(src, /lockfileAlignedToPinnedManifest/));
test('captures SHA-256 fingerprints', () => assert.match(src, /sha256\(/));
test('candidate export refuses overwrite', () => assert.match(src, /flag: 'wx'/));
test('does not perform network fetch', () => assert.match(src, /networkAccessAttempted: false/));
test('does not install dependencies', () => assert.match(src, /installExecuted: false/));
test('does not build API', () => assert.match(src, /buildExecuted: false/));
test('production clearance stays false', () => assert.match(src, /productionCleared: false/));
test('writes provenance sidecar', () => assert.match(src, /PROVENANCE\.json/));
test('report path is declared', () => assert.match(src, /PHASE205_AUTHORITATIVE_LOCKFILE_HANDOFF_REPORT\.json/));
const r = cp.spawnSync(process.execPath, [script], { cwd: root, encoding: 'utf8', timeout: 12000 });
test('default mode reports missing source inputs safely', () => assert.equal(r.status, 2, r.stderr));
test('report is generated', () => assert.ok(fs.existsSync(reportPath)));
const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
test('report identifies phase 205', () => assert.equal(report.phase, 205));
test('report does not claim production clearance', () => assert.equal(report.productionCleared, false));
test('report does not claim network access', () => assert.equal(report.networkAccessAttempted, false));
test('report identifies required inputs', () => assert.ok(report.blockers.some(x => x.includes('--repo') && x.includes('--expected-remote') && x.includes('--commit'))));
console.log(`Phase 205 contract assertions: ${passed}/24 passed`);
